// Fail fast with a clear message instead of ever producing an unsigned or debug-signed release.
val releaseSigningTasks = setOf(
    "validateSigningRelease", "packageRelease", "assembleRelease",
    "bundleRelease", "signReleaseBundle", "packageReleaseBundle",
)
tasks.configureEach {
    if (name in releaseSigningTasks) {
        doFirst {
            if (!releaseSigningReady) {
                throw GradleException(
                    "Release signing credentials are missing. Provide ANDROID_KEYSTORE_PATH, " +
                        "ANDROID_KEYSTORE_PASSWORD, ANDROID_KEY_ALIAS and ANDROID_KEY_PASSWORD " +
                        "(or an uncommitted keystore.properties). Debug signing is never used for release.",
                )
            }
        }
    }
}

